/**
 * Postgres connection pool — shared across all Clara modules.
 * DATABASE_URL must be set in .env before this module is imported.
 */

import pg from 'pg';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';
import dotenv from 'dotenv';

const __dirname = dirname(fileURLToPath(import.meta.url));
dotenv.config({ path: join(__dirname, '..', '.env') });

const { Pool } = pg;

let _pool = null;

export function getPool() {
  if (!_pool) {
    _pool = new Pool({
      connectionString: process.env.DATABASE_URL,
      max: 10,
      idleTimeoutMillis: 30000,
    });
    _pool.on('error', (err) => {
      console.error('Postgres pool error:', err.message);
    });
  }
  return _pool;
}

export async function query(sql, params = []) {
  const pool = getPool();
  const client = await pool.connect();
  try {
    return await client.query(sql, params);
  } finally {
    client.release();
  }
}

// ── Schema bootstrap ──────────────────────────────────────────────────────────
// Called once on server startup. Safe to run multiple times (IF NOT EXISTS).

export async function bootstrapSchema() {
  await query(`
    CREATE TABLE IF NOT EXISTS businesses (
      id            TEXT PRIMARY KEY,
      owner_name    TEXT,
      business_type TEXT,
      realm_id      TEXT UNIQUE,
      created_at    TIMESTAMPTZ DEFAULT NOW(),
      updated_at    TIMESTAMPTZ DEFAULT NOW()
    )
  `);

  await query(`
    CREATE TABLE IF NOT EXISTS qbo_tokens (
      realm_id           TEXT PRIMARY KEY,
      access_token       TEXT NOT NULL,
      refresh_token      TEXT NOT NULL,
      expires_at         TIMESTAMPTZ NOT NULL,
      refresh_expires_at TIMESTAMPTZ NOT NULL,
      created_at         TIMESTAMPTZ DEFAULT NOW(),
      updated_at         TIMESTAMPTZ DEFAULT NOW()
    )
  `);

  await query(`
    CREATE TABLE IF NOT EXISTS telegram_sessions (
      chat_id         BIGINT PRIMARY KEY,
      stage           TEXT NOT NULL DEFAULT 'welcome',
      business_id     TEXT,
      owner_name      TEXT,
      muted           BOOLEAN DEFAULT FALSE,
      custom_stickies JSONB DEFAULT '[]',
      follow_up_at    TIMESTAMPTZ,
      partial_fields  JSONB,
      created_at      TIMESTAMPTZ DEFAULT NOW(),
      updated_at      TIMESTAMPTZ DEFAULT NOW()
    )
  `);

  await query(`
    CREATE TABLE IF NOT EXISTS customer_wikis (
      chat_id    BIGINT PRIMARY KEY,
      pages      JSONB NOT NULL DEFAULT '{}',
      updated_at TIMESTAMPTZ DEFAULT NOW()
    )
  `);

  // business_wikis — keyed by business_id so all channels (Telegram + MCP) share one wiki
  await query(`
    CREATE TABLE IF NOT EXISTS business_wikis (
      business_id TEXT PRIMARY KEY,
      pages       JSONB NOT NULL DEFAULT '{}',
      updated_at  TIMESTAMPTZ DEFAULT NOW()
    )
  `);

  // One-time migration: copy existing customer_wikis rows into business_wikis via telegram_sessions
  await query(`
    INSERT INTO business_wikis (business_id, pages, updated_at)
    SELECT ts.business_id, cw.pages, cw.updated_at
    FROM customer_wikis cw
    JOIN telegram_sessions ts ON cw.chat_id = ts.chat_id
    WHERE ts.business_id IS NOT NULL
    ON CONFLICT (business_id) DO NOTHING
  `);

  // Phase 3: capability framework cache (one per business type, generated by AI)
  await query(`
    CREATE TABLE IF NOT EXISTS capability_frameworks (
      business_type TEXT PRIMARY KEY,
      framework     JSONB NOT NULL,
      created_at    TIMESTAMPTZ DEFAULT NOW()
    )
  `);

  // Phase 3: per-business capability scores (Layer 2 conversational)
  await query(`
    CREATE TABLE IF NOT EXISTS capability_assessments (
      business_id   TEXT NOT NULL,
      capability_id TEXT NOT NULL,
      score         INT CHECK (score BETWEEN 1 AND 5),
      evidence      TEXT,
      source        TEXT DEFAULT 'layer2_conversation',
      assessed_at   TIMESTAMPTZ DEFAULT NOW(),
      PRIMARY KEY (business_id, capability_id)
    )
  `);

  // Phase 3: store business_type + probe state in telegram sessions
  await query(`ALTER TABLE telegram_sessions ADD COLUMN IF NOT EXISTS business_type TEXT`);
  await query(`ALTER TABLE telegram_sessions ADD COLUMN IF NOT EXISTS pending_probe JSONB DEFAULT NULL`);
  await query(`ALTER TABLE telegram_sessions ADD COLUMN IF NOT EXISTS last_probe_at TIMESTAMPTZ DEFAULT NULL`);

  // Per-user MCP API keys
  await query(`
    CREATE TABLE IF NOT EXISTS mcp_api_keys (
      id           SERIAL PRIMARY KEY,
      key_hash     TEXT UNIQUE NOT NULL,
      key_prefix   TEXT NOT NULL,
      owner_label  TEXT,
      chat_id      BIGINT,
      realm_id     TEXT,
      created_at   TIMESTAMPTZ DEFAULT NOW(),
      last_used_at TIMESTAMPTZ,
      revoked_at   TIMESTAMPTZ
    )
  `);

  await query(`CREATE INDEX IF NOT EXISTS mcp_api_keys_chat_idx ON mcp_api_keys (chat_id)`);

  // One-time key pickup: lets MCP callers (e.g. Hermes) claim their QBO key without
  // manual copy-paste. Token is generated by onboard_clara, resolved by claim_api_key.
  // raw_key stored briefly (≤1h) then nulled on claim.
  await query(`
    CREATE TABLE IF NOT EXISTS key_pickups (
      token       TEXT PRIMARY KEY,
      raw_key     TEXT,
      realm_id    TEXT,
      created_at  TIMESTAMPTZ DEFAULT NOW(),
      claimed_at  TIMESTAMPTZ
    )
  `);

  // Phase A governance audit trail
  await query(`
    CREATE TABLE IF NOT EXISTS agent_actions (
      id          SERIAL PRIMARY KEY,
      chat_id     BIGINT,
      business_id TEXT NOT NULL,
      action_type TEXT NOT NULL,
      agent       TEXT NOT NULL,
      context     JSONB,
      draft_text  TEXT NOT NULL,
      created_at  TIMESTAMPTZ DEFAULT NOW(),
      viewed_at   TIMESTAMPTZ
    )
  `);

  await query(`
    CREATE INDEX IF NOT EXISTS agent_actions_business_idx ON agent_actions (business_id)
  `);

  // Vigil Score: owner-answered questions (one row per question per business)
  await query(`
    CREATE TABLE IF NOT EXISTS vigil_answers (
      id          SERIAL PRIMARY KEY,
      realm_id    TEXT NOT NULL,
      question_id TEXT NOT NULL,
      answer      TEXT,
      answered_at TIMESTAMPTZ DEFAULT NOW(),
      UNIQUE (realm_id, question_id)
    )
  `);

  await query(`CREATE INDEX IF NOT EXISTS vigil_answers_realm_idx ON vigil_answers (realm_id)`);

  // Vigil Score: computed score snapshots (append-only; latest is canonical)
  await query(`
    CREATE TABLE IF NOT EXISTS vigil_scores (
      id              SERIAL PRIMARY KEY,
      realm_id        TEXT NOT NULL,
      computed_at     TIMESTAMPTZ DEFAULT NOW(),
      industry_code   TEXT,
      scores          JSONB,
      composite       NUMERIC(3,1),
      dollar_gaps     JSONB,
      top_action      JSONB,
      raw_snapshot    JSONB,
      answer_snapshot JSONB
    )
  `);

  await query(`CREATE INDEX IF NOT EXISTS vigil_scores_realm_idx ON vigil_scores (realm_id)`);

  console.log('DB schema ready');
}
